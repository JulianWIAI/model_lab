/**
 * audit-tests.mjs — generate a test audit table for Phase 9.
 *
 * Scope: test files added or modified between phase-8c and phase-9b
 *   (git diff phase-8c phase-9b --name-only -- tests/).
 *
 * For each test in scope:
 *   - Test name (grep: /test\(\s*[`'"](.*?)[`'"]/)
 *   - First tolerance found in the test body (parsed)
 *   - Anchor source from file header comment
 *   - PRESENT (tol ≤ 1e-6 or exact boolean/throw), WEAK (1e-6 < tol < 1e-3), MISSING
 *
 * Also appends:
 *   git diff phase-9 phase-9b -- tests/ | grep -E '^[+-].*test\('
 *
 * Writes: docs/reviews/phase-9-test-audit.md
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { execSync } from 'node:child_process';

const REPO = new URL('..', import.meta.url).pathname.replace(/\/$/, '');

// --- Scope: files changed between phase-8c and phase-9b ---
let scopeFiles;
try {
  const out = execSync(
    'git diff phase-8c phase-9b --name-only -- tests/',
    { cwd: REPO, encoding: 'utf-8' }
  ).trim();
  scopeFiles = out.split('\n').filter(Boolean).map(f => join(REPO, f)).sort();
} catch (e) {
  console.error('Failed to compute scope via git diff:', e.message);
  process.exit(1);
}

// --- Extract test names via regex ---
function extractTests(content) {
  const tests = [];
  const re = /test\(\s*[`'"]([\s\S]*?)[`'"]/g;
  let m;
  while ((m = re.exec(content)) !== null) {
    tests.push(m[1]);
  }
  return tests;
}

// --- Extract first tolerance value from a region of code ---
function extractTolerance(region) {
  const patterns = [
    /(\d+(?:\.\d+)?e-\d+)/i,      // 1e-12, 4.5e-7
    /<\s*([\d.]+e[+-]?\d+)/i,      // < 1e-6
    /±\s*([\d.e+-]+)/,             // ± 1e-5
    /tol(?:erance)?\s*[:=]\s*([\d.e+-]+)/i,
  ];
  for (const p of patterns) {
    const m = region.match(p);
    if (m) return m[1] ?? m[0];
  }
  return null;
}

// --- Extract anchor source from header comment block ---
function extractAnchorSource(content) {
  const header = content.match(/^\/\*\*([\s\S]*?)\*\//);
  if (header) {
    const h = header[1];
    const m = h.match(/[Aa]nchors?\s+(?:from|:)\s+(.+)/);
    if (m) return m[1].trim();
    if (/CODATA/i.test(h)) return 'CODATA 2018 exact';
    if (/algebraic|exact|formula/i.test(h)) return 'algebraic';
  }
  return '(see header)';
}

// --- Classify a (tolerance, region) pair ---
function classify(tol, region) {
  // Exact boolean / throw tests are PRESENT with no tolerance needed
  if (!tol) {
    if (/assert\.throws/.test(region)) return 'PRESENT';
    if (/=== true|=== false|=== null/.test(region)) return 'PRESENT';
    if (/strictEqual/.test(region)) return 'PRESENT';
    // assert.ok with Math.abs is PRESENT (tolerance parsed elsewhere or exact)
    if (/Math\.abs/.test(region) || /< 1e-/.test(region)) return 'PRESENT';
    return 'MISSING';
  }
  const val = parseFloat(tol);
  if (isNaN(val)) return 'MISSING';
  if (val <= 1e-6) return 'PRESENT';
  if (val < 1e-3) return 'WEAK';
  return 'MISSING';
}

// --- Main ---
const rows = [];

for (const file of scopeFiles) {
  const relPath = relative(REPO, file);
  let content;
  try { content = readFileSync(file, 'utf-8'); } catch { continue; }

  const tests = extractTests(content);
  const anchorSource = extractAnchorSource(content);

  for (const testName of tests) {
    const idx = content.indexOf(testName);
    const region = content.slice(idx, Math.min(idx + 600, content.length));
    const tol = extractTolerance(region);
    const status = classify(tol, region);
    rows.push({ file: relPath, testName, tolerance: tol ?? '(none)', anchorSource, status });
  }
}

// --- Build markdown ---
const counts = { PRESENT: 0, WEAK: 0, MISSING: 0 };
for (const r of rows) counts[r.status]++;

let md = `# Phase 9 Test Audit\n\n`;
md += `Generated by \`tools/audit-tests.mjs\` on ${new Date().toISOString().slice(0, 10)}.\n`;
md += `Scope: test files modified between \`phase-8c\` and \`phase-9b\`.\n\n`;
md += `Total tests in scope: ${rows.length}\n\n`;
md += `| Status | Count |\n|---|---|\n`;
md += `| PRESENT | ${counts.PRESENT} |\n`;
md += `| WEAK | ${counts.WEAK} |\n`;
md += `| MISSING | ${counts.MISSING} |\n\n`;

md += `## Full table\n\n`;
md += `| file | test name | tolerance | anchor source | status |\n`;
md += `|---|---|---|---|---|\n`;

for (const r of rows) {
  const name = r.testName.replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const src  = r.anchorSource.replace(/\|/g, '\\|');
  md += `| ${r.file} | ${name} | ${r.tolerance} | ${src} | ${r.status} |\n`;
}

// --- git diff phase-9 → phase-9b (what changed in 9b) ---
md += `\n## Tests added/removed between \`phase-9\` and \`phase-9b\`\n\n`;
md += `\`git diff phase-9 phase-9b -- tests/ | grep -E '^[+-].*test\\('\`\n\n`;

try {
  const diff = execSync(
    `git diff phase-9 phase-9b -- tests/`,
    { cwd: REPO, encoding: 'utf-8', maxBuffer: 10 * 1024 * 1024 }
  );
  const added   = diff.split('\n').filter(l => l.startsWith('+') && !l.startsWith('+++') && l.includes('test('));
  const removed = diff.split('\n').filter(l => l.startsWith('-') && !l.startsWith('---') && l.includes('test('));

  if (added.length) {
    md += `### Added (${added.length})\n\n\`\`\`\n`;
    for (const l of added) md += l + '\n';
    md += `\`\`\`\n\n`;
  }
  if (removed.length) {
    md += `### Removed (${removed.length})\n\n\`\`\`\n`;
    for (const l of removed) md += l + '\n';
    md += `\`\`\`\n\n`;
  }
  if (!added.length && !removed.length) {
    md += `No test lines added or removed between phase-9 and phase-9b.\n`;
  }
} catch (e) {
  md += `(git diff failed: ${e.message})\n`;
}

const outPath = join(REPO, 'docs/reviews/phase-9-test-audit.md');
writeFileSync(outPath, md);
console.log(`Wrote ${outPath.replace(REPO + '/', '')} (${rows.length} tests in scope)`);
console.log(`PRESENT: ${counts.PRESENT}  WEAK: ${counts.WEAK}  MISSING: ${counts.MISSING}`);
