/**
 * gen-test-audit-phase10b.mjs — generate Phase 10b test audit table.
 * Writes: docs/reviews/phase-10b-test-audit.md
 * Diffs: phase-10..HEAD
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { execSync } from 'node:child_process';

const REPO = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const TEST_DIR = join(REPO, 'tests');
const OUT = join(REPO, 'docs/reviews/phase-10b-test-audit.md');

function findTests(dir) {
  const results = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, e.name);
    if (e.isDirectory()) results.push(...findTests(full));
    else if (e.name.endsWith('.test.js')) results.push(full);
  }
  return results.sort();
}

function extractTests(content) {
  const tests = [];
  const re = /(?:^|\n)\s*(?:test|it)\(\s*['"`]([\s\S]*?)['"`]/g;
  let m;
  while ((m = re.exec(content)) !== null) tests.push(m[1]);
  return tests;
}

function extractTolerance(body) {
  const patterns = [
    /(\d+(?:\.\d+)?e-\d+)/i,
    /<\s*([\d.]+e[+-]?\d+)/i,
    /\u00b1\s*([\d.e+-]+)/,
  ];
  for (const p of patterns) {
    const m = body.match(p);
    if (m) return m[1] || m[0];
  }
  return null;
}

function classify(tol, body) {
  if (!tol) {
    if (/assert\.throws|strictEqual/.test(body)) return 'PRESENT';
    if (/Math\.abs/.test(body)) return 'PRESENT';
    return 'WEAK';
  }
  const val = parseFloat(tol);
  if (isNaN(val)) return 'WEAK';
  if (val <= 1e-6) return 'PRESENT';
  if (val < 1e-3) return 'WEAK';
  return 'MISSING';
}

const files = findTests(TEST_DIR);
const rows = [];

for (const file of files) {
  const rel = relative(REPO, file);
  const content = readFileSync(file, 'utf-8');
  const tests = extractTests(content);
  for (const name of tests) {
    const idx = content.indexOf(name);
    const body = content.slice(Math.max(0, idx - 20), idx + 500);
    const tol = extractTolerance(body);
    rows.push({
      file: rel,
      name: name.replace(/\n/g, ' ').slice(0, 80),
      tol: tol || '(none)',
      status: classify(tol, body),
    });
  }
}

const counts = { PRESENT: 0, WEAK: 0, MISSING: 0 };
for (const r of rows) counts[r.status]++;

let md = '# Phase 10b Test Audit\n\n';
md += 'Generated by `tools/gen-test-audit-phase10b.mjs` on ' + new Date().toISOString().slice(0, 10) + '.\n\n';
md += 'Total tests: ' + rows.length + '\n\n';
md += '| Status | Count |\n|---|---|\n';
md += '| PRESENT | ' + counts.PRESENT + ' |\n';
md += '| WEAK | ' + counts.WEAK + ' |\n';
md += '| MISSING | ' + counts.MISSING + ' |\n\n';
md += '## Full table\n\n';
md += '| file | test name | tolerance | status |\n|---|---|---|---|\n';
for (const r of rows)
  md += '| ' + r.file + ' | ' + r.name.replace(/\|/g, '\\|') + ' | ' + r.tol + ' | ' + r.status + ' |\n';

// diff phase-10..HEAD
try {
  const diff = execSync('git diff phase-10 HEAD -- tests/', {
    cwd: REPO, encoding: 'utf-8', maxBuffer: 10 * 1024 * 1024,
  });
  const added   = diff.split('\n').filter(l => /^\+.*(?:test|it)\(/.test(l));
  const removed = diff.split('\n').filter(l => /^-.*(?:test|it)\(/.test(l));
  md += '\n## Tests added phase-10 → phase-10b (' + added.length + ')\n\n```\n';
  for (const l of added) md += l + '\n';
  md += '```\n';
  if (removed.length) {
    md += '\n## Tests removed (' + removed.length + ')\n\n```\n';
    for (const l of removed) md += l + '\n';
    md += '```\n';
  }
} catch (e) {
  md += '\n(git diff failed: ' + e.message + ')\n';
}

writeFileSync(OUT, md);
console.log('Wrote ' + OUT);
console.log('rows=' + rows.length + '  PRESENT=' + counts.PRESENT + '  WEAK=' + counts.WEAK + '  MISSING=' + counts.MISSING);
